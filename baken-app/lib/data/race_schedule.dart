/// 日程表に載っている重賞 1レース分
class ScheduledRace {
  const ScheduledRace({
    required this.date,
    required this.preset,
    required this.raceNo,
    required this.estimated,
  });

  final DateTime date;
  final RacePreset preset;

  /// レース番号（障害重賞など、決まっていないものは null）
  final int? raceNo;

  /// 2026年の日程から推定した日付か
  final bool estimated;

  String get name => preset.name;
  String get venue => preset.venue ?? '';
}

DateTime _day(DateTime d) => DateTime(d.year, d.month, d.day);

String _iso(DateTime d) =>
    '${d.year.toString().padLeft(4, '0')}-'
    '${d.month.toString().padLeft(2, '0')}-'
    '${d.day.toString().padLeft(2, '0')}';

/// [date] を含む開催週（火曜〜翌月曜）。月曜の祝日開催を前の土日と同じ週にする。
({DateTime start, DateTime end}) raceWeekOf(DateTime date) {
  final d = _day(date);
  final start = d.subtract(Duration(days: (d.weekday - DateTime.tuesday) % 7));
  return (start: start, end: start.add(const Duration(days: 6)));
}

/// 2026年の何日にあたるか（同じ曜日・同じ週。364日＝52週ずつずらす）
DateTime _toScheduleYear(DateTime d) {
  var x = _day(d);
  while (x.year > scheduleYear) {
    x = x.subtract(const Duration(days: 364));
  }
  while (x.year < scheduleYear) {
    x = x.add(const Duration(days: 364));
  }
  return x;
}

/// その日に行われる重賞（日程表がない年は推定）
List<ScheduledRace> gradedRacesOn(DateTime date) {
  final d = _day(date);
  final key = _toScheduleYear(d);
  final names = _graded2026[_iso(key)] ?? const [];
  final estimated = d.year != scheduleYear;
  return [
    for (final n in names)
      if (presetByName(n) case final p?)
        ScheduledRace(
          date: d,
          preset: p,
          raceNo: _raceNoOverride[n] ?? (p.surface == '障害' ? null : 11),
          estimated: estimated,
        ),
  ];
}

/// [date] を含む開催週の重賞（日付順・格の高い順）
List<ScheduledRace> gradedRacesInWeek(DateTime date) {
  final w = raceWeekOf(date);
  final out = <ScheduledRace>[];
  for (var i = 0; i < 7; i++) {
    final races = gradedRacesOn(w.start.add(Duration(days: i)))
      ..sort((a, b) => a.preset.grade.index.compareTo(b.preset.grade.index));
    out.addAll(races);
  }
  return out;
}

/// その週の開催日（重賞がある日と、土日）
List<DateTime> raceDaysInWeek(DateTime date) {
  final w = raceWeekOf(date);
  return [
    for (var i = 0; i < 7; i++)
      if (w.start.add(Duration(days: i)) case final d
          when d.weekday == DateTime.saturday ||
              d.weekday == DateTime.sunday ||
              gradedRacesOn(d).isNotEmpty)
        d,
  ];
}

